function sp(input: Omit<Species, "conservation" | "status_label" | "verified" | "review_status" | "data_status" | "updated_at" | "media_ids" | "audio_ids"> & {
  conservation: Omit<Species["conservation"], "status_label" | "source"> & { source: SourceRef };
}): Species {
  return {
    ...input,
    conservation: {
      ...input.conservation,
      status_label: STATUS_LABEL[input.conservation.status] ?? "未评估",
    },
    media_ids: [],
    audio_ids: [],
    data_status: "curated",
    review_status: "editorial",
    verified: false,
    updated_at: "2026-11-01",
  };
}

