import type { Species } from "@/lib/types";

const RETRIEVED = "2026-11-01";

const STATUS_LABEL: Record<string, string> = {
  LC: "无危",
  NT: "近危",
  VU: "易危",
  EN: "濒危",
  CR: "极危",
  NE: "未评估",
};

const iucn = (scientific: string, year: number, status: string) => ({
  source_name: "IUCN Red List",
  source_url: `https://www.iucnredlist.org/search?query=${encodeURIComponent(scientific)}`,
  license: "CC BY-NC-SA 3.0（引用需遵守 IUCN 条款）",
  retrieved_at: RETRIEVED,
  published_at: `${year}`,
  verified: false,
  review_status: "editorial" as const,
  note: `保护等级为编辑整理（${status} / ${year}），接入 IUCN API 后需复核分类单元与评估版本。`,
});

const source = (name: string, url: string, note: string) => ({
  source_name: name,
  source_url: url,
  license: "引用链接，未复制全文",
  retrieved_at: RETRIEVED,
  verified: false,
  review_status: "editorial" as const,
  note,
});

const wiki = (title: string) => source("Wikipedia", `https://en.wikipedia.org/wiki/${encodeURIComponent(title.replace(/ /g, "_"))}`, "辅助核对分类、形态与习性。");

function make(
  input: Omit<Species, "conservation" | "media_ids" | "audio_ids" | "data_status" | "review_status" | "verified" | "updated_at"> & {
    conservation: Omit<Species["conservation"], "status_label" | "source"> & { source: Species["conservation"]["source"] };
  }
): Species {
  return {
    ...input,
    conservation: { ...input.conservation, status_label: STATUS_LABEL[input.conservation.status] ?? "未评估" },
    media_ids: [],
    audio_ids: [],
    data_status: "curated",
    review_status: "editorial",
    verified: false,
    updated_at: RETRIEVED,
  };
}

